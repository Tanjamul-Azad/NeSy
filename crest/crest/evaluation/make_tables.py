"""Canonical table generator -- the ONLY source of experimental tables.

Enforces the canonical-table rule in `docs/DEFINITION_OF_DONE.md` (condition 6):
every table in the paper and in the thesis is generated from the committed
result JSONs, never typed by hand and never copied out of a chat message. One
canonical source, two rendered outputs.

Why this exists as code rather than as a habit: a hand-typed table cell is
unfalsifiable. It survives every review, every re-analysis, and every
correction to the underlying result, because nothing connects it to the data
any more. Several numbers in this project have already been corrected after
publication-to-ourselves (the reachability soundness figure, the coverage gate,
the near-miss share); had those lived in a hand-typed LaTeX table, the
corrections would not have propagated.

Outputs LaTeX fragments to `paper/tables/` and `report/tables/`, byte-identical
to each other, so paper and thesis can never drift apart on a number.

Run: python -m crest.evaluation.make_tables
"""

import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

PROJECT_ROOT = Path(__file__).resolve().parents[2]
REPO_ROOT = PROJECT_ROOT.parent
sys.path.insert(0, str(PROJECT_ROOT))

LOGS = PROJECT_ROOT / "experiments" / "logs"
OUT_DIRS = [REPO_ROOT / "paper" / "tables", REPO_ROOT / "report" / "tables"]

MODEL_ORDER = ["Llama-3.1-8B", "gpt-4o-mini", "gpt-4o"]
DATASET_LABEL = {"folio": "FOLIO", "proofwriter": "ProofWriter",
                 "prontoqa": "PrOntoQA", "contractnli": "ContractNLI"}


def provenance() -> str:
    """Every generated table carries the commit it was generated from, so a
    stale table in a draft is detectable rather than invisible."""
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                             cwd=REPO_ROOT, capture_output=True, text=True,
                             check=True).stdout.strip()
    except Exception:
        sha = "UNKNOWN"
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return (f"% GENERATED by crest/crest/evaluation/make_tables.py -- DO NOT EDIT BY HAND\n"
            f"% commit {sha} | {stamp}\n"
            f"% Editing this file directly violates docs/DEFINITION_OF_DONE.md condition 6.\n")


def _pct(x, digits=0):
    return "--" if x is None else f"{100 * x:.{digits}f}"


def table_capability_matrix() -> str:
    """Main result: silent-failure prevalence and severity by dataset x model."""
    src = LOGS / "cross_summary.json"
    if not src.exists():
        return ""
    rows = json.loads(src.read_text(encoding="utf-8"))
    if isinstance(rows, dict):
        rows = rows.get("rows", rows.get("cells", []))

    lines = [provenance(),
             r"\begin{tabular}{llrrrrr}", r"\toprule",
             r"Dataset & Model & $n$ & Acc. & Silent & Wrong-dir. & Under-det. \\",
             r"\midrule"]
    for ds in ["folio", "proofwriter", "prontoqa"]:
        for m in MODEL_ORDER:
            r = next((x for x in rows
                      if x.get("dataset") == ds and x.get("model") == m), None)
            if not r:
                continue
            acc, sil = r.get("accuracy", {}), r.get("silent", {})
            wd, ud = r.get("wrong_direction", {}), r.get("under_determination", {})
            lines.append(
                f"{DATASET_LABEL[ds]} & {m} & {r.get('n_gradeable','--')} & "
                f"{_pct(acc.get('point'))}\\% & \\textbf{{{_pct(sil.get('point'))}\\%}} & "
                f"{_pct(wd.get('point'))}\\% & {_pct(ud.get('point'))}\\% \\\\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines.append(r"\end{tabular}")
    return "\n".join(lines)


def table_detector() -> str:
    """CREST-D signal performance, including the signal-2 negative result."""
    src = LOGS / "attributor_eval.json"
    if not src.exists():
        return ""
    payload = json.loads(src.read_text(encoding="utf-8"))
    cells = payload.get("cells", payload) if isinstance(payload, dict) else payload

    lines = [provenance(),
             r"\begin{tabular}{llrrrr}", r"\toprule",
             r"Dataset & Model & $n$ & Base & S2 recall & S2 lift \\",
             r"\midrule"]
    seen = set()
    for r in cells:
        key = (r.get("dataset"), r.get("model"))
        if key in seen:
            continue
        seen.add(key)
        c, s2 = r.get("combined", {}), r.get("sig2", {})
        lift = s2.get("lift")
        lift_s = "--" if lift is None else f"{lift:.2f}"
        lines.append(
            f"{DATASET_LABEL.get(r.get('dataset'), r.get('dataset'))} & {r.get('model')} & "
            f"{r.get('n_analysable','--')} & {_pct(c.get('base_rate'))}\\% & "
            f"{_pct(s2.get('recall'))}\\% & {lift_s} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def table_contractnli_ceiling() -> str:
    """The contract-indexed ceiling. Never rendered without its contract names
    (docs/PREREG_E1_formalizability.md, E1.0 consequence 1)."""
    src = LOGS / "contractnli_ceiling_probe.json"
    if not src.exists():
        return ""
    payload = json.loads(src.read_text(encoding="utf-8"))
    matches, n = payload.get("matches", {}), payload.get("n", 0)
    label = {"literal": r"$C_L$ (literal)", "charitable": r"$C_C$ (charitable)",
             "assumption_augmented": "assumption-augmented (excluded)"}
    lines = [provenance(),
             r"\begin{tabular}{lrr}", r"\toprule",
             r"Admissibility contract & Recovered & Rate \\", r"\midrule"]
    for k in ("literal", "charitable", "assumption_augmented"):
        if k in matches:
            lines.append(f"{label[k]} & {matches[k]}/{n} & {100*matches[k]/n:.0f}\\% \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


TABLES = {
    "capability_matrix": table_capability_matrix,
    "detector_signals": table_detector,
    "contractnli_ceiling": table_contractnli_ceiling,
}


def main():
    for d in OUT_DIRS:
        d.mkdir(parents=True, exist_ok=True)

    written = 0
    for name, fn in TABLES.items():
        content = fn()
        if not content:
            print(f"  skip {name}: source JSON not present yet")
            continue
        for d in OUT_DIRS:
            (d / f"{name}.tex").write_text(content, encoding="utf-8")
        written += 1
        print(f"  wrote {name}.tex -> {len(OUT_DIRS)} locations")

    print(f"\n{written}/{len(TABLES)} tables generated, identical in paper/ and report/.")
    print("Any number in either document that is not in these files was typed by")
    print("hand and violates docs/DEFINITION_OF_DONE.md condition 6.")


if __name__ == "__main__":
    main()
